import { useEffect, useState, type ReactNode } from "react";
import { getCurrentWindow } from "@tauri-apps/api/window";
import { isTauri, systemMenu, VERSION, type Lang } from "./platform";
import { strings } from "./i18n";
import { Mark } from "./ui";

/**
 * Своя титульная полоса. Окно рисуется без системной рамки (`decorations:
 * false` в `tauri.conf.json`) — с ней над панелью состояния стояла бы вторая
 * полоса с тем же названием, и главное, что окно рассказывает, начиналось бы
 * со второго этажа сверху.
 *
 * Что рамка давала бесплатно и теперь наше:
 *  - перетаскивание — `data-tauri-drag-region` на пустых местах полосы. Именно
 *    на пустых: атрибут, накрывающий кнопки, отдал бы их нативному drag-циклу,
 *    а тот съедает клик. Двойной клик по тем же местам разворачивает окно —
 *    это tao делает сам;
 *  - тяга за края для ресайза остаётся нативной: `WM_NCHITTEST` у безрамочного
 *    окна tao обрабатывает сам, плагина для этого не нужно;
 *  - три кнопки — здесь.
 *
 * Права `core:window:allow-{start-dragging,minimize,toggle-maximize,
 * is-maximized,close}` дописаны в `capabilities/default.json`: в наборе
 * `core:default` их нет, и без них вызовы молча отклоняются.
 *
 * Здесь же живут версия, обновление и вход в настройки. Раньше это был подвал
 * окна — целая плита под тем, что читают раз в месяц, пока список профилей
 * делил остаток высоты с журналом. В полосе они занимают то место, которое всё
 * равно пустует, а на ширине плашки из трея имя и версия уходят совсем
 * (`.tb-name`, `.tb-version` в `index.css`): кнопки окна важнее.
 *
 * Значки — свои `<svg>`, а не глифы шрифта: `Segoe MDL2 Assets` есть не на
 * всякой системе, а отсутствующий глиф — это пустой квадрат вместо «закрыть».
 * «Закрыть» красится в `fault`, а не в `closed`: янтарь запертого канала —
 * штатное состояние продукта, а не разрушительное действие.
 *
 * В браузере (разработка без Tauri) полоса остаётся, но без трёх кнопок и без
 * перетаскивания: рамку там рисует сам браузер, а настройки и обновления нужны
 * и в разработке.
 *
 * У плашки из трея полосы нет вовсе (`App.tsx` её не рисует): сворачивать
 * некуда, разворачивать не во что, двигать нельзя — плашка стоит у значка.
 * Остальное у неё уже есть без полосы: «открыть окно» и «настройки» — в меню
 * значка, а прячут её Esc, потеря фокуса и повторный клик по значку.
 *
 *  - системное меню («Переместить», «Размер», «Свернуть», «Закрыть») — правый
 *    клик по полосе и Alt+Space. Рисует его Windows, а мы только зовём
 *    (`systemMenu`): свои пункты пришлось бы и переводить, и запрещать по
 *    состоянию окна — оба раза хуже, чем у системы. Alt+Space слушается на
 *    документе, потому что фокус в этот момент почти никогда не на полосе.
 */
export function TitleBar({
  title,
  lang,
  /** Тег вышедшего релиза, если окно о нём уже спросило. Само оно наружу не
   *  ходит: кнопка появляется только после ручной проверки в настройках. */
  update,
  /** Открывает установщик вышедшего релиза — то же самое, что кнопка
   *  «Скачать» в настройках, одним нажатием. Раньше здесь открывались сами
   *  настройки: кнопка звала обновиться и показывала вместо обновления ещё
   *  одну кнопку. Действие живёт в `useReleases`. */
  onUpdate,
  settingsOpen,
  onSettings,
}: {
  title: string;
  lang: Lang | undefined;
  update: string | null;
  onUpdate: () => void;
  settingsOpen: boolean;
  onSettings: () => void;
}) {
  const desktop = isTauri();
  const s = strings(lang);
  const [maximized, setMaximized] = useState(false);

  useEffect(() => {
    if (!desktop) return;
    let disposed = false;
    let unlisten: (() => void) | null = null;
    const win = getCurrentWindow();
    const sync = () =>
      void win.isMaximized().then((value) => {
        if (!disposed) setMaximized(value);
      });
    sync();
    // Развернуть можно и мимо кнопки — двойным кликом, Win+↑, снапом к краю.
    // Иконка обязана следовать за окном, а не за своим кликом.
    void win.onResized(sync).then((fn) => (disposed ? fn() : (unlisten = fn)));
    return () => {
      disposed = true;
      unlisten?.();
    };
  }, [desktop]);

  // Alt+Space — жест всего окна, а не полосы: фокус в этот момент стоит там,
  // где человек работал, и повесить его на полосу значило бы не завести вовсе.
  useEffect(() => {
    if (!desktop) return;
    const key = (e: KeyboardEvent) => {
      if (!e.altKey || e.code !== "Space") return;
      e.preventDefault();
      void systemMenu(false);
    };
    document.addEventListener("keydown", key);
    return () => document.removeEventListener("keydown", key);
  }, [desktop]);

  const run = (action: "minimize" | "toggleMaximize" | "close") => void getCurrentWindow()[action]();

  return (
    <header
      onContextMenu={(e) => {
        // Меню окна — только за то, за что окно и таскают: за пустые места
        // полосы, знак и имя. Правый клик по кнопке открыл бы его вместо того,
        // чего человек ждёт от кнопки, поэтому признак тут тот же, что и у
        // перетаскивания, — он и стоит ровно на тех местах.
        if (!(e.target as HTMLElement).hasAttribute("data-tauri-drag-region")) return;
        e.preventDefault();
        void systemMenu(true);
      }}
      data-tauri-drag-region
      className="flex h-8 shrink-0 items-center gap-2 overflow-hidden border-b border-edge bg-surface ps-3"
    >
      {/* Знак остаётся, когда имя и версия уже ушли (`.tb-name` на узкой
          ширине): 16 px не мешают кнопкам, а без него полоса перестаёт
          говорить, чьё это окно. Обёртка нужна ради перетаскивания — тянут за
          неё, а не за svg, поэтому у знака событий мыши нет вовсе. */}
      <span data-tauri-drag-region className="flex shrink-0 items-center text-accent">
        <Mark className="pointer-events-none" />
      </span>
      <span data-tauri-drag-region className="tb-name engraved min-w-0 truncate text-muted">
        {title}
      </span>
      {/* Версия — такое же показание прибора, как задержка и байты: число
          моноширинное, подпись ушла в подсказку. */}
      <span className="tb-version shrink-0 font-mono text-[11px] tabular-nums text-muted" title={s.version}>
        {VERSION}
      </span>
      <span data-tauri-drag-region className="min-w-0 flex-1" />
      {/* Точка перед надписью: новость видно и краем глаза, не читая строку. */}
      {update != null && (
        <button
          type="button"
          className={`${TB_BUTTON} flex items-center gap-1.5 px-2.5 text-accent hover:bg-surface-2`}
          title={s.updateTo(update)}
          onClick={onUpdate}
        >
          <span className="size-1.5 rounded-full bg-accent" />
          {s.updateTo(update)}
        </button>
      )}
      {/* Настройки — такая же кнопка полосы, как «свернуть» и «закрыть»: одна
          высота, одна ширина, одна подсветка под курсором. Своя, поменьше и без
          подложки, рядом с ними читалась как пустое место. Открытые настройки
          кнопка держит нажатой — иначе полоса не отличает «там сейчас» от «туда
          можно».

          Шестерня, а не ползунки: ползунки значат «покрутить прямо здесь», а
          кнопка открывает целую панель.

          Шестернёй её делает отверстие, а не зубья — это проверено рисованием.
          Сплошная втулка с восемью отростками читается солнцем, сколько зубья ни
          укорачивай: у солнца ровно такой силуэт. Стоит проколоть середину, и та
          же картинка становится шестернёй.

          Рисованы значки заливкой, а не штрихом, и это смена решения. Штриховая
          шестерня на 12 пикселях держалась на двух волосках: обод в 1.1 и
          просвет отверстия в 1.3 — на 1× просвет замыливался в точку, то есть
          выходило то самое солнце. Заливка эту зависимость снимает: дырка тут
          подпуть, а не тонкая окружность, и живёт она правилом обхода
          (`fillRule="evenodd"`), а не цветом поверхности поверх.

          Цвет поверхности сюда по-прежнему нельзя, и запрет тот же, что и был:
          под курсором подложка меняется, и залитое ею показало бы прошлый фон.
          Заливка здесь только `currentColor` — она и есть цвет надписи, который
          подсветка меняет заодно со всем остальным.

          Раз залит один значок, залиты все четыре: ряд читается как один ряд,
          и одна сплошная фигура среди трёх волосяных перевешивала бы его целиком
          — проверено рисованием. Перемычка у «свернуть», «развернуть» и
          «закрыть» — 5 из 50, то есть 1.2 px: на 6 линии грузнеют и квадрат
          превращается в рамку, на 4 ряд снова разъезжается с шестернёй.

          Сетка у всех четырёх одна — 50, а не 12: шестерня нарисована по ней, и
          пересчитывать кривые в двенадцатые ради единообразия значит вносить
          ошибку округления туда, где её никто не заметит. */}
      <WindowButton label={s.settings} title={s.settingsHint} onClick={onSettings} pressed={settingsOpen}>
        <path d="M47.16,21.221l-5.91-0.966c-0.346-1.186-0.819-2.326-1.411-3.405l3.45-4.917c0.279-0.397,0.231-0.938-0.112-1.282l-3.889-3.887c-0.347-0.346-0.893-0.391-1.291-0.104l-4.843,3.481c-1.089-0.602-2.239-1.08-3.432-1.427l-1.031-5.886C28.607,2.35,28.192,2,27.706,2h-5.5c-0.49,0-0.908,0.355-0.987,0.839l-0.956,5.854c-1.2,0.345-2.352,0.818-3.437,1.412l-4.83-3.45c-0.399-0.285-0.942-0.239-1.289,0.106L6.82,10.648c-0.343,0.343-0.391,0.883-0.112,1.28l3.399,4.863c-0.605,1.095-1.087,2.254-1.438,3.46l-5.831,0.971c-0.482,0.08-0.836,0.498-0.836,0.986v5.5c0,0.485,0.348,0.9,0.825,0.985l5.831,1.034c0.349,1.203,0.831,2.362,1.438,3.46l-3.441,4.813c-0.284,0.397-0.239,0.942,0.106,1.289l3.888,3.891c0.343,0.343,0.884,0.391,1.281,0.112l4.87-3.411c1.093,0.601,2.248,1.078,3.445,1.424l0.976,5.861C21.3,47.647,21.717,48,22.206,48h5.5c0.485,0,0.9-0.348,0.984-0.825l1.045-5.89c1.199-0.353,2.348-0.833,3.43-1.435l4.905,3.441c0.398,0.281,0.938,0.232,1.282-0.111l3.888-3.891c0.346-0.347,0.391-0.894,0.104-1.292l-3.498-4.857c0.593-1.08,1.064-2.222,1.407-3.408l5.918-1.039c0.479-0.084,0.827-0.5,0.827-0.985v-5.5C47.999,21.718,47.644,21.3,47.16,21.221z M25,32c-3.866,0-7-3.134-7-7c0-3.866,3.134-7,7-7s7,3.134,7,7C32,28.866,28.866,32,25,32z" />
      </WindowButton>
      {desktop && (
        <>
          <WindowButton label={s.minimizeWindow} onClick={() => run("minimize")}>
            <rect x="8" y="22.5" width="34" height="5" rx="2.5" />
          </WindowButton>
          <WindowButton label={maximized ? s.restoreWindow : s.maximizeWindow} onClick={() => run("toggleMaximize")}>
            {maximized ? (
              <>
                {/* Переднее окно рамкой и заднее уголком: заливкой «поверх» тут
                    не нарисовать — под курсором подложка меняется. Уголок
                    поэтому обведён по своему контуру, а не спрятан под передним
                    окном заплаткой цвета фона. */}
                <path d="M8 17h25v25H8zM13 22h15v15H13z" />
                <path d="M17 8h25v25h-5V13H17z" />
              </>
            ) : (
              <path d="M9 9h32v32H9zM14 14h22v22H14z" />
            )}
          </WindowButton>
          <WindowButton label={s.closeWindow} onClick={() => run("close")} danger>
            <rect x="4.35" y="22.5" width="41.3" height="5" rx="2.5" transform="rotate(45 25 25)" />
            <rect x="4.35" y="22.5" width="41.3" height="5" rx="2.5" transform="rotate(-45 25 25)" />
          </WindowButton>
        </>
      )}
    </header>
  );
}

/** Общий вид кнопки титульной полосы. Кнопки стоят вплотную и читаются как
 *  один ряд, поэтому высота, реакция на курсор и её плавность обязаны быть
 *  одной строкой на всех: разъедутся — и ряд рассыплется на разнородные
 *  детали. Подсветка сюда не входит намеренно, у «закрыть» она своя.
 *  Кнопка обновления берёт отсюда только контейнер: цвет у неё свой,
 *  акцентный, и под курсором он остаётся — им она и говорит, зачем она тут. */
const TB_BUTTON = "h-8 shrink-0 transition-colors";
const TB_HOVER = "hover:bg-surface-2 hover:text-ink";

function WindowButton({
  label,
  title,
  onClick,
  danger,
  pressed,
  children,
}: {
  label: string;
  title?: string;
  onClick: () => void;
  danger?: boolean;
  pressed?: boolean;
  children: ReactNode;
}) {
  return (
    <button
      type="button"
      aria-label={label}
      aria-pressed={pressed}
      title={title ?? label}
      onClick={onClick}
      className={`${TB_BUTTON} grid w-11 place-items-center ${
        pressed ? "bg-surface-2 text-ink" : "text-muted"
      } ${danger ? "hover:bg-fault hover:text-bg" : TB_HOVER}`}
    >
      {/* Рисуем заливкой, а не штрихом: на 12 пикселях волосок в 1.1 съедает
          сам себя — просвет внутри фигуры схлопывается, и отверстие шестерни
          замыливается в точку. Заливка обязана быть `currentColor` и никогда
          цветом поверхности: подсветка под курсором меняет подложку, и залитое
          ею показало бы прошлый фон. Дырки — правилом обхода, отдельным
          подпутём внутри фигуры. Сторож — `the_title_bar_glyphs_share_one_grid`. */}
      <svg
        width="12"
        height="12"
        viewBox="0 0 50 50"
        fill="currentColor"
        fillRule="evenodd"
        aria-hidden="true"
      >
        {children}
      </svg>
    </button>
  );
}
