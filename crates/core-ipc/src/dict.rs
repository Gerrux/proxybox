//! есть перевод на русский, поэтому таблицы RU не существует, а незаполненный
//! перевод молча превращается не в пустоту и не в ключ вида `err.no_profile`,
//! а в читаемую русскую фразу.
//!
//! Так сделано ради одного свойства: добавить язык — значит добавить сюда
//! таблицу и ветку в `translate`, и ничего больше. До этого строки лежали
//! парами прямо в вызове (`t(ru, en)`), и третий язык означал бы правку всех
//! ста пятидесяти восьми мест. Плата за переезд — текст уехал из места вызова;
//! поэтому ключ оставлен человеческой фразой, а не идентификатором: в коде
//! по-прежнему написано то, что человек увидит, просто не на всех языках сразу.
//!
//! Порядок ключей во всех таблицах один и тот же — как встретились в коде.
//! Полноту и порядок стережёт `every_line_has_its_translation`: он вычитывает
//! литералы `t("…")` и `tf!("…")` из исходников всех крейтов и оболочки и
//! требует, чтобы каждый нашёлся в каждой таблице. Без него забытая строка
//! молчит — и молчит она на языке, которого читатель не знает.

