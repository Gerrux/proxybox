    /// Значки титульной полосы обязаны быть одной семьёй: одна сетка, одна
    /// заливка, одна коробка. Ряд из четырёх кнопок читается как один ряд, и
    /// одна фигура, нарисованная иначе прочих, перевешивает его целиком —
    /// сплошная шестерня среди трёх волосяных линий именно это и делала.
    ///
    /// Заливка обязана быть `currentColor`. Цвет поверхности сюда нельзя: под
    /// курсором подложка меняется, и залитое ею показало бы прошлый фон — а
    /// заметно это только наведением, то есть почти никогда.
    ///
    /// Отверстие шестерни обязано остаться отверстием. Держится оно вторым
    /// подпутём и правилом обхода; пропадёт любое из двух — и вместо шестерни
    /// выйдет сплошная блямба, потому что дырку в залитой фигуре больше нечем
    /// сделать. Компилятора у фронтенда нет — сверяем текстом.
    #[test]
    fn the_title_bar_glyphs_share_one_grid() {
        let bar = include_str!("../../../ui/app-shell/src/TitleBar.tsx");
        // Не первое вхождение «<svg», а первый настоящий тег: в шапке модуля
        // это слово стоит прозой, и разбор упирался в неё.
        let svg = bar
            .split("<svg")
            .skip(1)
            .filter_map(|s| s.split('>').next())
            .find(|head| head.contains("viewBox"))
            .expect("значки полосы рисует один <svg> внутри WindowButton");
        assert!(svg.contains("fill=\"currentColor\""), "значки полосы залиты не цветом надписи");
        assert!(svg.contains("fillRule=\"evenodd\""), "без правила обхода дырка в шестерне зальётся");
        assert!(!svg.contains("stroke"), "в полосе снова штрих: на 12 px он съедает просветы фигур");
        let grid = svg
            .split("viewBox=\"")
            .nth(1)
            .and_then(|s| s.split('"').next())
            .expect("у значков полосы есть своя сетка");

        // Значки живут только внутри кнопок полосы: знак приложения рисует
        // `Mark` в `ui.tsx`, и своей сетки у него сколько угодно.
        let row = bar.split("<WindowButton").skip(1).collect::<Vec<_>>();
        assert!(row.len() >= 4, "в полосе меньше четырёх кнопок: их {}", row.len());
        let side: f64 = grid.split_whitespace().last().and_then(|s| s.parse().ok()).expect("сетка квадратная");

        // Шестерня — единственная фигура с дыркой, и обе её половины обязаны
        // остаться: контур и подпуть отверстия.
        let gear = row.iter().find(|b| b.contains("s.settings")).expect("шестерня стоит на кнопке настроек");
        let d = gear
            .split("d=\"")
            .nth(1)
            .and_then(|s| s.split('"').next())
            .expect("шестерня нарисована путём");
        assert!(
            d.matches('M').count() + d.matches('m').count() >= 2,
            "у шестерни один подпуть: отверстие пропало, и осталась блямба"
        );

        // Ни одна фигура не имеет права торчать за сетку: `svg` обрезает по
        // вьюпорту молча, а срезанный на пиксель угол глазом не читается.
        // Считаем по прямым числам — координатам прямоугольников и абсолютным
        // точкам путей; кривые шестерни лежат внутри своего контура и отдельной
        // проверки не требуют.
        for shape in row.iter().flat_map(|b| b.split("<rect").skip(1)) {
            for name in ["x=\"", "y=\"", "width=\"", "height=\""] {
                let v: f64 = shape
                    .split(name)
                    .nth(1)
                    .and_then(|s| s.split('"').next())
                    .and_then(|s| s.parse().ok())
                    .unwrap_or_else(|| panic!("у прямоугольника полосы нет {name}"));
                assert!(v >= 0.0 && v <= side, "фигура полосы за сеткой: {name}{v} при стороне {side}");
            }
        }
    }

