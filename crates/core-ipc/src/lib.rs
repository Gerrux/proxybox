        // "proxybox" уже занято сайдкаром pg-cli (bundle.externalBin ниже).
        // Поставь кто-нибудь "mainBinaryName": "proxybox" — и сайдкары,
        // копируемые вторыми (debian.rs: главный бинарник первым, сайдкары
