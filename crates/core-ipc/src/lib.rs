    ///
    /// Держит порядок служба, а не окно, по той же причине, что и звёздочку:
    /// список — это то, чем пользуются каждый день, и заново расставлять его
    /// на второй машине человек не станет. Целиком, а не «переставь этот в ту
    /// позицию»: у окна на руках весь список, а у службы после такой команды не
    /// осталось бы способа проверить, что обе стороны считают порядок
    /// одинаковым.
    ///
    /// Пустой список — «этот порядок не трогать», как пустой `node` в
    /// `EditProfile`. Перенесли подписку — имена профилей приезжают пустыми:
    /// иначе перенос группы заморозил бы в ручной порядок то, что до сих пор
