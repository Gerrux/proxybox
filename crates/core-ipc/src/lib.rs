    /// окна. Прокрутки вбок у окна нет — плита обрезает по `overflow-hidden`, —
    /// поэтому уехавший переключатель не просто не виден: до него нельзя
    /// дотянуться, и настройка становится недоступной молча.
    ///
    /// Ровно это и делал `shrink-0` на блоке управления: он запрещал сжатие
    /// вовсе, блок брал ширину по содержимому и держал её шире окна. В 380 px
