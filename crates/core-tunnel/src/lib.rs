    /// Локальные имена обязан разрешать роутер, а не сервер человека. После
    /// перехвата DNS весь запрос машины уходит на `remote`, и `nas.lan` вместе
    /// с ним: там он не разрешится, зато уедет наружу.
    ///
    /// Резолвер и правила заводятся всегда вместе: ссылка на несуществующий тег
    /// — отказ разбора, тег без ссылок — мусор. Без TUN нет ни того, ни другого:
    /// перехвата там нет, и локальные имена до нас не доходят.
    #[test]
    fn local_names_are_resolved_by_the_router() {
        let cfg = build_config(&node(), &Options::default());
        let servers = cfg["dns"]["servers"].as_array().unwrap();
        let lan = servers
            .iter()
            .find(|s| s["tag"] == "lan")
            .unwrap_or_else(|| panic!("резолвера локальных имён нет: {servers:#?}"));
        assert_eq!(lan["type"], "dhcp", "адрес роутера в конфиге не назвать — он у каждого свой");

        let rules = cfg["dns"]["rules"].as_array().unwrap();
        assert!(!rules.is_empty(), "резолвер есть, а правил к нему нет — мусор в конфиге");
        // Локальные имена обязаны разбираться **до** FakeIP: пропусти их следом,
        // и `nas.lan` получил бы фальшивый адрес, то есть маршрут в туннель
        // вместо роутера в соседней комнате.
        let fake = rules.iter().position(|r| r["server"] == "fake").expect("правила FakeIP нет");
        for rule in &rules[..fake] {
            assert_eq!(rule["server"], "lan", "впереди FakeIP стоят только локальные имена: {rule}");
        }
        // После FakeIP осталось ровно одно правило — пустой NOERROR на AAAA, и
        // оно обязано стоять именно там: раньше него оно съело бы AAAA
        // локальных имён, позже — не съело бы ничего.
        assert_eq!(fake, rules.len() - 2, "после FakeIP место только у пустого AAAA: {rules:#?}");
        assert_eq!(rules[fake + 1]["action"], "predefined", "{rules:#?}");
        let suffixes = rules.iter().find_map(|r| r["domain_suffix"].as_array()).expect("суффиксы");
        assert!(suffixes.iter().any(|s| s == "lan"));
        // Односложные имена `domain_suffix` не ловит, а зовут так чаще всего.
        assert!(rules.iter().any(|r| r["domain_regex"][0] == "^[^.]+$"), "{rules:#?}");

        // Без TUN — ни резолвера, ни правил, и это одно условие на двоих.
        let bare = build_config(&node(), &Options { tun: false, ..Default::default() });
        assert!(bare["dns"]["servers"].as_array().unwrap().iter().all(|s| s["tag"] != "lan"));
        assert!(bare["dns"]["rules"].as_array().unwrap().is_empty(), "{}", bare["dns"]["rules"]);
    }

    /// Адрес выдаётся здесь и сразу, а не спрашивается через туннель.
    ///
    /// Имена в этом продукте разрешал сервер на том конце (`dns.final: remote`
    /// с `detour: proxy`), запасного локального пути не было намеренно — и
    /// поэтому каждое имя стоило целого круга по каналу. Просадка канала убивала
    /// не байты, а имена, то есть страницу до её начала; на живой машине это
    /// выглядело как «всё работает, кроме браузеров» — остальные к тому моменту
    /// сидят на разрешённых именах, а браузер спрашивает новые непрерывно.
    ///
    /// FakeIP это снимает целиком: адрес из `198.18.0.0/15` отдаётся из памяти,
    /// а настоящее имя едет с самим соединением и разрешается на том конце.
    ///
    /// Три вещи здесь обязаны держаться вместе, и каждая проверена на живом
    /// 1.13.19 (A → `198.18.0.2` за 0 мс, AAAA → пустой NOERROR за 0 мс):
    ///
    /// - пустой NOERROR на AAAA отдельным правилом (`action: predefined`) —
    ///   иначе AAAA уходит на `remote`, то есть в туннель, и круг возвращается
    ///   ровно туда, откуда его убирали. Делал это `strategy: ipv4_only` на
    ///   правиле FakeIP, пока 1.14 не объявил ручку устаревшей и не начал
    ///   падать на ней насмерть; ответ от замены не изменился;
    /// - у пула нет `inet6_range` — фальшивый AAAA увёл бы приложение в IPv6,
    ///   которого наш TUN не держит, и соединение умерло бы, не начавшись;
    /// - `independent_cache` — одно имя у `fake` и у `lan` имеет разные ответы.
    ///
    /// Адрес самого узла фальшивым не станет: его разрешает
    /// `default_domain_resolver: { server: local }`, а тот назван резолвером
    /// поимённо и правила `dns.rules` не проходит вовсе — проверено запуском,
    /// узел разрешился настоящим адресом. Сорвись это, туннель не поднялся бы
    /// никогда: набирать было бы нечего.
    #[test]
    fn fake_addresses_are_handed_out_locally() {
        let cfg = build_config(&node(), &Options::default());
        let servers = cfg["dns"]["servers"].as_array().unwrap();
        let fake = servers
            .iter()
            .find(|s| s["tag"] == "fake")
            .unwrap_or_else(|| panic!("пула FakeIP нет: {servers:#?}"));
        assert_eq!(fake["type"], "fakeip");
        assert_eq!(fake["inet4_range"], FAKE_RANGE);
        assert!(fake["inet6_range"].is_null(), "фальшивый AAAA уводит в IPv6, которого у TUN нет: {fake}");
        assert_eq!(cfg["dns"]["independent_cache"], true, "общий кэш смешал бы ответы `fake` и `lan`");

        let rules = cfg["dns"]["rules"].as_array().unwrap();
        let rule = rules
            .iter()
            .find(|r| r["server"] == "fake")
            .expect("правила FakeIP нет")
            .clone();
        let types: Vec<&str> = rule["query_type"].as_array().unwrap().iter().map(|t| t.as_str().unwrap()).collect();
        assert_eq!(types, ["A"], "фальшивый адрес выдаётся только на A: {rule}");
        assert!(rule["strategy"].is_null(), "1.14 отвергает `strategy` в действии правила фатально: {rule}");

        // Вторая половина той же мысли: AAAA обязан получать пустой NOERROR, и
        // именно отдельным правилом. Пропадёт оно — запрос уедет на `remote`,
        // то есть кругом по каналу, ради ответа, которым всё равно не
        // воспользоваться: адреса v6 у TUN нет.
        let empty = rules
            .iter()
            .find(|r| r["action"] == "predefined")
            .expect("пустого ответа на AAAA нет: он уйдёт в туннель");
        let types: Vec<&str> = empty["query_type"].as_array().unwrap().iter().map(|t| t.as_str().unwrap()).collect();
        assert_eq!(types, ["AAAA"], "пустым обязан быть только AAAA: {empty}");
        assert_eq!(empty["rcode"], "NOERROR", "{empty}");
        assert!(empty["answer"].is_null(), "ответ обязан быть пустым: {empty}");

        // Порядок: локальные имена впереди обоих, иначе `nas.lan` получил бы
        // фальшивый адрес вместо роутера, а его AAAA — пустоту.
        let lan = rules.iter().position(|r| r["server"] == "lan").unwrap();
        let fake_at = rules.iter().position(|r| r["server"] == "fake").unwrap();
        let empty_at = rules.iter().position(|r| r["action"] == "predefined").unwrap();
        assert!(lan < fake_at && lan < empty_at, "локальные имена обязаны идти первыми: {rules:#?}");

        // Файла кэша нет и быть не должно: соответствие «фальшивый адрес — имя»
        // это список всех посещённых сайтов, и на диске ему не место.
        assert!(cfg["experimental"]["cache_file"].is_null(), "{}", cfg["experimental"]);

        // Без TUN фальшивых адресов не бывает: раздавать их некому — ни TUN, ни
        // перехвата, а проба и окна профилей ходят SOCKS'ом по имени.
        let bare = build_config(&node(), &Options { tun: false, ..Default::default() });
        assert!(bare["dns"]["servers"].as_array().unwrap().iter().all(|s| s["tag"] != "fake"));
        assert!(bare["dns"]["rules"].as_array().unwrap().is_empty(), "{}", bare["dns"]["rules"]);
    }

    /// Конфиг обязан не только разбираться, но и **запускаться**, и это разные
    /// вещи. `sing-box check` проверяет разбор: `detour: "direct"` на пустом
    /// тогда ещё `direct`-outbound он пропускал молча, а служба на нём падала
    /// при старте с «detour to an empty direct outbound makes no sense». Ровно
    /// так и случилось — поймано запуском уже после того, как проверка конфига
    /// дала зелёный свет.
    ///
    /// Он же отвечает на второй вопрос того же рода: примет ли sing-box пустой
    /// `outbounds` у WireGuard, где узел живёт в `endpoints`. 1.13.19
    /// принимает и стартует.
    ///
    /// Без TUN и на свободных портах: прав на TUN у тестов нет, а постоянные
    /// порты столкнулись бы с живой службой на машине разработчика.
    #[test]
    fn the_config_actually_starts() {
        let node = core_config::parse("trojan://p@127.0.0.1:1").unwrap().node;
        for tun in [false, true] {
            let Ok((socks_port, api_port)) = free_port().and_then(|a| Ok((a, free_port()?))) else {
                return;
            };
            let mut cfg = build_config(&node, &Options { tun, socks_port, api_port, ..Default::default() });
            if tun {
                // Сам TUN тесту не поднять — прав нет. Но секция `dns` при TUN
                // другая (появляется резолвер из DHCP), и её старт проверить
                // надо: снимаем инбаунд и правила, которые на него ссылаются, —
                // остальное поднимается как обычно.
                cfg["inbounds"].as_array_mut().unwrap().retain(|i| i["type"] != "tun");
                cfg["route"]["rules"].as_array_mut().unwrap().retain(|r| r["inbound"][0] != "tun-in");
            }
            let dir = std::env::temp_dir().join(format!("pg-start-check-{tun}"));
            let _ = std::fs::remove_dir_all(&dir);
            match Tunnel::start(&cfg, &dir) {
                Ok(mut live) => live.stop(),
                // sing-box не установлен — проверять нечем; отличаем по тексту,
                // потому что любой другой отказ здесь обязан валить тест.
                Err(e) if e.to_string().contains("не запускается") || e.to_string().contains("cannot start") => return,
                Err(e) => panic!("конфиг (tun={tun}) разбирается, но служба на нём не поднимается: {e}"),
            }
        }
    }

