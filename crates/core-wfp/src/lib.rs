//! Каркас драйвера: пока умеет только загрузиться и выгрузиться.
//!
//! Зачем он вообще — целиком в `docs/wfp.md`. Коротко: в охвате «выбранные
//! приложения» разницу между охватами держит не конфиг sing-box, а этот
//! драйвер. Невыбранных он уводит из туннеля bind-редиректом на физический
//! интерфейс, выбранных запирает на `ALE_AUTH_CONNECT`, пока служба не
//! подтвердила туннель. Матчер по процессу из конфига при этом исчезает — с ним
//! и расход, который сегодня несёт вся машина.
//!
//! # Это не собиралось
//!
//! Ни одной строчки отсюда компилятор не видел: WDK живёт на Windows, а среда,
//! где каркас написан, — Linux без clang и без прав его поставить. Поэтому здесь
//! ровно две точки входа, и ни одной строчки сверх них: непроверенного
//! unsafe-кода в ядре должно быть столько, сколько нельзя не написать. Как
//! собрать и чем проверить — `BUILD-WINDOWS.md`, и до первой удачной сборки
//! считать написанное правдой нельзя.
//!
//! # Что дальше
//!
//! Регистрация callout'а — следующий шаг, и делается он уже за приглашением
//! WDK, а не здесь. Последовательность (проверена по документации, см.
//! «Источники» в `docs/wfp.md`): устройство для callout'а,
//! `FwpsCalloutRegister3` (не `...0`: слои редиректа требуют `classifyFn1` и
//! выше), `FwpmEngineOpen0`, `FwpmCalloutAdd0` и фильтр на
//! `FWPM_LAYER_ALE_BIND_REDIRECT_V4/V6`. Отдельно и позже — `ALE_AUTH_CONNECT`
//! для запрета выбранных: там ни редиректа, ни контекстов, чистые permit/block.

#![no_std]

#[cfg(not(test))]
extern crate wdk_panic;

#[cfg(not(test))]
#[global_allocator]
static GLOBAL_ALLOCATOR: wdk_alloc::WdkAllocator = wdk_alloc::WdkAllocator;

use wdk_sys::{NTSTATUS, PCUNICODE_STRING, PDRIVER_OBJECT, STATUS_SUCCESS};

/// Точка входа. Имя обязано быть ровно `DriverEntry`: его ищет загрузчик, а
/// искажённое Rust'ом имя он не найдёт и молча откажется грузить драйвер.
///
/// # Safety
///
/// Зовёт ядро при загрузке; `driver` — живой объект драйвера.
#[export_name = "DriverEntry"]
pub unsafe extern "system" fn driver_entry(
    driver: PDRIVER_OBJECT,
    _registry_path: PCUNICODE_STRING,
) -> NTSTATUS {
    // Выгрузку заводим сразу, ещё пустую: без `DriverUnload` драйвер снимается
    // только перезагрузкой, а на отладке его снимают по десять раз на день.
    (*driver).DriverUnload = Some(driver_unload);
    STATUS_SUCCESS
}

/// Снять за собой всё, что завели. Заводить пока нечего — но пустой обработчик
/// это ровно то, что делает драйвер выгружаемым.
///
/// # Safety
///
/// Зовёт ядро при выгрузке.
unsafe extern "C" fn driver_unload(_driver: PDRIVER_OBJECT) {}
